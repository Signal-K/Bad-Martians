// Command playtest plays Haphazard Martians headlessly and prints a balance
// report for the expedition economy (KES-517 shared budget, KES-518 par reward).
//
//	go run ./cmd/playtest                       # shipped numbers
//	go run ./cmd/playtest -start 30,33,36,40 -par 0,2,4 -out docs/playtest/latest.md
//
// It drives the real physics (game.Run) with bot pilots over a pool of
// generated rovers, then plays seeded expeditions with three player types
// through the real Expedition rules. Same flags, same report.
package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"strconv"
	"strings"
	"time"

	"github.com/signal-k/haphazard-martians/game"
)

func ints(s string, def int) []int {
	if s == "" {
		return []int{def}
	}
	var out []int
	for _, f := range strings.Split(s, ",") {
		n, err := strconv.Atoi(strings.TrimSpace(f))
		if err != nil {
			fmt.Fprintf(os.Stderr, "bad number %q\n", f)
			os.Exit(2)
		}
		out = append(out, n)
	}
	return out
}

func main() {
	designs := flag.Int("designs", 160, "rovers in the generated pool")
	n := flag.Int("n", 300, "expeditions per player type and economy")
	seed := flag.Uint64("seed", 1, "seed for designs and players")
	start := flag.String("start", "", "starting credits to try, comma separated (default: shipped)")
	par := flag.String("par", "", "under-par rewards to try, comma separated (default: shipped)")
	noSalvage := flag.Bool("no-salvage", false, "turn off the undamaged-win salvage credits")
	traces := flag.Int("traces", 1, "example expeditions to print per player type (shipped economy)")
	out := flag.String("out", "", "also write the report to this file")
	flag.Parse()

	t0 := time.Now()
	pool := game.GenerateDesigns(*designs, *seed)
	lab := game.NewLab(game.ExpeditionLevels, pool)

	var w io.Writer = os.Stdout
	var b strings.Builder
	if *out != "" {
		w = io.MultiWriter(os.Stdout, &b)
	}
	p := func(f string, a ...any) { fmt.Fprintf(w, f+"\n", a...) }

	shipped := game.ShippedEconomy()
	p("# Expedition playtest")
	p("")
	p("Seed %d, %d generated rovers, %d pilots (%s), %d expeditions per player type. Shipped economy: %s.",
		*seed, len(pool), len(game.Pilots), pilotNames(), *n, shipped)
	p("")
	p("## Stages")
	p("")
	p("| Stage | Level | Par | Legal rovers | Win with a bot | Under par | Cheapest win | Cheapest under par | Fastest |")
	p("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
	for i, r := range lab.Reports {
		p("| %d | %s | %.0fs | %d | %d (%.0f%%) | %d | %s | %s | %s |", i+1, r.Level.Name, r.Level.Par, r.Legal,
			r.Winners, pctf(r.Winners, r.Legal), r.UnderPar, cr(r.CheapestWin), cr(r.CheapestPar), secs(r.FastestWin))
	}
	p("")
	p("Minimum valid rover: %d credits.", game.MinRover())

	p("")
	p("## Player types")
	p("")
	p("- **planner** builds the cheapest rover that works, keeping a survivor that still works.")
	p("- **racer** builds the fastest rover it can afford, to beat par.")
	p("- **tinkerer** builds at random; after a crash it has an even chance of copying a rover that works.")

	starts, pars := ints(*start, shipped.StartingCredits), ints(*par, shipped.UnderParCredits)
	p("")
	p("## Economies")
	p("")
	p("| Start | Par + | Player | Complete | Crashes / run | Par awards / run | Salvage credits / run | Credits left (winners) | Failed at 1 / 2 / 3 | Avg score |")
	p("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
	for _, s := range starts {
		for _, pr := range pars {
			ec := game.Economy{StartingCredits: s, UnderParCredits: pr, Salvage: !*noSalvage}
			res := lab.Play(ec, *n, *seed)
			for _, kind := range game.PlayerTypes {
				t := res[kind]
				left := "-"
				if t.Completed > 0 {
					left = fmt.Sprintf("%.1f", float64(t.CreditsLeft)/float64(t.Completed))
				}
				p("| %d | %d | %s | %.0f%% | %.2f | %.2f | %.2f | %s | %d / %d / %d | %.0f |", s, pr, kind, t.Rate(),
					per(t.Crashes, t.Runs), per(t.ParAwards, t.Runs), per(t.SalvageCredits, t.Runs), left,
					t.FailedAt[0], t.FailedAt[1], t.FailedAt[2], per(t.Score, t.Runs))
			}
		}
	}

	if *traces > 0 {
		p("")
		p("## Example expeditions (shipped economy)")
		for _, kind := range game.PlayerTypes {
			for i := 0; i < *traces; i++ {
				r := lab.PlayExpedition(kind, shipped, *seed+uint64(i))
				end := "failed"
				if r.Exp.Done {
					end = "completed"
				}
				p("")
				p("**%s #%d** (%s, score %d)", kind, i+1, end, r.Exp.Score)
				p("")
				for _, l := range r.Log {
					p("- %s", l)
				}
			}
		}
	}
	p("")
	p("_Generated by `go run ./cmd/playtest` in %s._", time.Since(t0).Round(time.Second))

	if *out != "" {
		if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func pilotNames() string {
	var s []string
	for _, p := range game.Pilots {
		s = append(s, p.Name)
	}
	return strings.Join(s, ", ")
}

func pctf(a, b int) float64 {
	if b == 0 {
		return 0
	}
	return 100 * float64(a) / float64(b)
}

func per(a, b int) float64 {
	if b == 0 {
		return 0
	}
	return float64(a) / float64(b)
}

func cr(c int) string {
	if c == 0 {
		return "none"
	}
	return fmt.Sprintf("%d cr", c)
}

func secs(s float64) string {
	if s == 0 {
		return "-"
	}
	return fmt.Sprintf("%.1fs", s)
}
